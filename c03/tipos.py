# Los cuatro tipos básicos y la función type()
lados = 6               # int: número entero
radio = 1.5             # float: número con parte decimal
nombre = "hexágono"     # str: cadena de texto
relleno = True          # bool: verdadero o falso
print(type(lados), type(radio))
print(type(nombre), type(relleno))
print(type(6), type(6.0), type("6"))
