# Operadores aritméticos
a = 17
b = 5
print(a + b, a - b, a * b)    # suma, resta y producto
print(a / b)                  # división: siempre da float
print(a // b, a % b)          # cociente entero y resto
print(a ** b)                 # potencia
print(2 + 3 * 4, (2 + 3) * 4) # prioridad de las operaciones
print(0.1 + 0.2)
