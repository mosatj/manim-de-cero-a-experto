# Rebanadas: lista[inicio:fin:paso] (fin NO se incluye)
letras = ["a", "b", "c", "d", "e", "f"]
print(letras[1:4])      # índices 1, 2 y 3
print(letras[:3])       # desde el principio
print(letras[3:])       # hasta el final
print(letras[::2])      # de dos en dos
print(letras[::-1])     # al revés
print(letras[-2:])      # los dos últimos
print("Manim"[1:3])     # también con cadenas
