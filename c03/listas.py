# Una lista guarda varios valores en orden
colores = ["rojo", "verde", "azul"]
print(colores[0])        # el primero tiene índice 0
print(colores[2])
print(colores[-1])       # índices negativos: desde el final
print(len(colores))
colores.append("amarillo")   # añade al final
colores[1] = "cian"          # las listas se pueden modificar
print(colores)
