# Cadenas: texto entre comillas
titulo = "Teorema de Pitágoras"
print("=" * 20)                   # repetir
print(titulo + "!")               # concatenar
print(len(titulo))                # número de caracteres
print(titulo[0], titulo[-1])      # primer y último carácter
print(titulo.upper())
print(titulo.replace("Pitágoras", "Tales"))
print(titulo.split())             # trocea en palabras
print("Pitágoras" in titulo)
