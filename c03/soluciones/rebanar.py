# Propuesto: índices y rebanadas sobre una lista de colores
colores = ["rojo", "naranja", "amarillo",
           "verde", "azul", "violeta"]
print("Primero:", colores[0])
print("Último:", colores[-1])
print("Los tres del medio:", colores[1:4])
print("Al revés:", colores[::-1])
print("Uno sí, uno no:", colores[::2])
